def draw_text(frame, x, y, text, color, scale=1):
    """Нарисовать текст в кадр pure_raster. x,y — левый верхний угол."""
    cx = x
    for ch in text.upper():
        glyph = GLYPHS.get(ch)
        if glyph is None:
            glyph = GLYPHS['?'] if '?' in GLYPHS else GLYPHS[' ']
        for row, bits in enumerate(glyph):
            for col in range(5):
                if bits & (1 << (4 - col)):
                    for sy in range(scale):
                        for sx in range(scale):
                            frame.set_pixel(cx + col*scale + sx,
                                            y + row*scale + sy,
                                            -1e-6, color)
        cx += 6 * scale
    return cx

def text_width(text, scale=1):
    return len(text) * 6 * scale
